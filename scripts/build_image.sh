#!/usr/bin/env bash
# Build qil-dev on the box. With --lock, resolve docker/requirements.in and write the exact
# versions to docker/requirements.lock first (then rebuild from the lock).
set -euo pipefail
cd "$(dirname "$0")/.."
if [ "${1:-}" = --lock ]; then
  cp docker/requirements.in docker/requirements.lock
  docker build -q -f docker/Dockerfile -t qil-dev:resolve . >/dev/null
  names=$(grep -v '^#' docker/requirements.in | sed '/^$/d' | tr '\n' ' ')
  docker run --rm qil-dev:resolve bash -c "pip freeze" > /tmp/qil-freeze.txt
  { echo "# Generated by scripts/build_image.sh --lock from docker/requirements.in; do not edit."
    for n in $names; do grep -i -E "^${n//-/[-_]}==" /tmp/qil-freeze.txt; done; } > docker/requirements.lock
  cat docker/requirements.lock
fi
docker build -q -f docker/Dockerfile -t qil-dev:latest .
docker run --rm qil-dev:latest pip check | tail -3 || true
